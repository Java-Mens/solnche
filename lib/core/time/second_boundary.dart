/// Задержка до следующей секундной границы системных часов: 1..1000 мс.
///
/// ТЗ FR-02: обновление времени должно быть синхронизировано с секундной
/// границей системных часов, чтобы цифры секунд не «дрожали» относительно
/// системных часов. Просыпаемся не раньше границы: к моменту пробуждения
/// `DateTime.now()` уже принадлежит новой секунде, поэтому усечение до
/// секунд в [DateTime] даёт ровно границу.
///
/// Чистая функция — вынесена отдельно для тестирования.
int delayToNextSecondBoundary(DateTime now) => 1000 - now.millisecond;
